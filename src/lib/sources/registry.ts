const registryMap = new Map<string, SourceRow>(
  SOURCE_REGISTRY_DATA.map((r) => [r.id, r])
);

export function loadRegistry(): Map<string, SourceRow> {
  return registryMap;
}

export function toCitation(sourceId: string): Citation | null {
  const row = registryMap.get(sourceId);
  if (!row) return null;
  return {
    title: row.title,
    url: row.landing_url,
    publisher: row.publisher,
    docType: row.doc_type,
    sourceEffectiveDate: row.source_effective_date || null,
    retrievedAt: row.fetched_at,
  };
}

export function educationalLink(kind: "investor_education" | "factsheet"): string {
  const id = kind === "investor_education" ? "amfi-investor-corner" : "monthly-factsheet-aug-2026";
  const row = registryMap.get(id);
  if (!row) return "https://www.amfiindia.com/investor";
  return row.landing_url;
}
